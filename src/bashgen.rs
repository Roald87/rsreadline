use crate::config::Config;
use crate::tty;

/// Builds the full `eval "$(rsreadline init bash)"` output: per-character
/// `bind -x` bindings that keep suggestions live as-you-type, a Backspace
/// binding, dynamic Up/Down rebinding between our suggestion-cycle handler
/// and bash's native history browsing, dynamic Tab rebinding between bash's
/// native completion and our no-op (once a suggestion is selected, Enter is
/// how it gets confirmed, not Tab), and a `PROMPT_COMMAND` hook that clears
/// the suggestion block before each new prompt.
pub fn generate(config: &Config) -> String {
    let exe_q = shell_single_quote(&current_exe_string());
    let clear_seq = dollar_quote(&tty::clear_sequence(config.max_suggestions));

    let mut lines: Vec<String> = Vec::new();

    lines.push("# Generated by `rsreadline init bash` — eval this in your .bashrc.".to_string());
    // Without this, readline continuously re-binds whatever key `stty erase`
    // points to (Backspace, almost always) back to its own default, ignoring
    // any bind/bind -x we issue for it — see ARCHITECTURE.md
    // ("Why bind-tty-special-chars is off") for how this was diagnosed.
    lines.push("bind 'set bind-tty-special-chars off'".to_string());
    // Empty _RSREADLINE_SEL means "nothing selected" — suggestions appear
    // unselected as you type; only Up/Down picks one. _RSREADLINE_QUERY is
    // what you actually typed, kept separate from READLINE_LINE because
    // Up/Down overwrites READLINE_LINE with a selection preview, and
    // cycling needs to keep matching against the real typed text, not that
    // preview. See ARCHITECTURE.md ("Selecting a suggestion").
    lines.push("_RSREADLINE_SEL=\"\"".to_string());
    lines.push("_RSREADLINE_QUERY=\"\"".to_string());
    lines.push("_RSREADLINE_BUSY=0".to_string());
    lines.push(r#"bind '"\e[A": previous-history'"#.to_string());
    lines.push(r#"bind '"\e[B": next-history'"#.to_string());
    // Nothing is selected at a fresh prompt, so Tab starts as bash's own
    // native completion (readline's default binding for it) — not our
    // suggestion box. __rsreadline_update below switches it to our no-op
    // once something gets selected, and back once the selection clears.
    lines.push(r#"bind '"\C-i": complete'"#.to_string());
    lines.push(String::new());

    // Enter is never rebound (bind -x can't intercept it and still trigger
    // bash's own accept-line), so without this, the suggestion block would
    // sit on screen, stale, for as long as the submitted command runs. This
    // DEBUG trap fires right before that command executes and clears it.
    // _RSREADLINE_BUSY guards against it also firing (and clearing) during
    // our own handlers' internal commands, not just the user's. Full
    // rationale in ARCHITECTURE.md ("Enter and the DEBUG-trap preexec hook").
    lines.push("# See ARCHITECTURE.md (\"Enter and the DEBUG-trap preexec hook\")".to_string());
    lines.push("# for why this function and the trap below it exist.".to_string());
    lines.push("__rsreadline_preexec() {".to_string());
    lines.push("    # Skip while one of our own handlers is still running —".to_string());
    lines.push("    # it owns the block and will redraw it itself when done.".to_string());
    lines.push("    [[ \"$_RSREADLINE_BUSY\" == 1 ]] && return".to_string());
    lines.push(format!("    printf '%s' {clear_seq} > /dev/tty"));
    lines.push("}".to_string());
    lines.push("trap __rsreadline_preexec DEBUG".to_string());
    lines.push(String::new());

    lines.push("__rsreadline_update() {".to_string());
    lines.push("    local direction=\"$1\" query point result sel count fill".to_string());
    lines.push("    if [[ \"$direction\" == none ]]; then".to_string());
    lines.push("        _RSREADLINE_QUERY=\"$READLINE_LINE\"".to_string());
    lines.push("        query=\"$READLINE_LINE\"".to_string());
    lines.push("        point=\"$READLINE_POINT\"".to_string());
    lines.push("    else".to_string());
    lines.push("        query=\"$_RSREADLINE_QUERY\"".to_string());
    lines.push("        point=${#_RSREADLINE_QUERY}".to_string());
    lines.push("    fi".to_string());
    lines.push(format!(
        "    result=$({exe_q} render \"$query\" \"$point\" \"$_RSREADLINE_SEL\" \"$direction\")"
    ));
    // \x01 (SOH), not a tab: bash's `read` treats IFS whitespace characters
    // (space/tab/newline) as collapsible even with a custom IFS, silently
    // dropping empty fields anywhere but the very end — verified directly:
    // `IFS=$'\t' read -r a b c <<< $'\t3\t'` gives a=3 b= c=, not a= b=3 c=.
    // Since `sel`/`fill` are legitimately empty on most calls (nothing
    // selected / no fill), tab-splitting silently corrupted them. \x01
    // can't plausibly appear in real command text and isn't whitespace, so
    // `read` splits on it literally.
    lines.push("    IFS=$'\\x01' read -r sel count fill <<< \"$result\"".to_string());
    lines.push("    _RSREADLINE_SEL=\"$sel\"".to_string());
    lines.push("    if [[ -n \"$fill\" ]]; then".to_string());
    lines.push("        READLINE_LINE=\"$fill\"".to_string());
    lines.push("        READLINE_POINT=${#READLINE_LINE}".to_string());
    lines.push("    fi".to_string());
    lines.push("    if [[ \"${count:-0}\" -gt 0 ]]; then".to_string());
    lines.push(r#"        bind -x '"\e[A": __rsreadline_up'"#.to_string());
    lines.push(r#"        bind -x '"\e[B": __rsreadline_down'"#.to_string());
    lines.push("    else".to_string());
    lines.push(r#"        bind '"\e[A": previous-history'"#.to_string());
    lines.push(r#"        bind '"\e[B": next-history'"#.to_string());
    lines.push("    fi".to_string());
    // Same dynamic-rebind trick, keyed on selection rather than match
    // count: nothing selected -> Tab stays bash's native completion;
    // something selected -> Tab is a no-op (Enter confirms instead).
    lines.push("    if [[ -n \"$_RSREADLINE_SEL\" ]]; then".to_string());
    lines.push(r#"        bind -x '"\C-i": __rsreadline_tab_noop'"#.to_string());
    lines.push("    else".to_string());
    lines.push(r#"        bind '"\C-i": complete'"#.to_string());
    lines.push("    fi".to_string());
    lines.push("}".to_string());
    lines.push(String::new());

    // Every function below that's bound directly to a key (i.e. every one of
    // these five) wraps its whole body in _RSREADLINE_BUSY=1 / =0. That's the
    // guard __rsreadline_preexec checks above — see the comment block by
    // `trap ... DEBUG` for the full explanation. __rsreadline_update doesn't
    // need its own copy of this: it's only ever called from one of these five,
    // so the flag is already 1 for its whole duration.
    lines.push("__rsreadline_up() {".to_string());
    lines.push("    _RSREADLINE_BUSY=1".to_string());
    lines.push("    __rsreadline_update up".to_string());
    lines.push("    _RSREADLINE_BUSY=0".to_string());
    lines.push("}".to_string());
    lines.push("__rsreadline_down() {".to_string());
    lines.push("    _RSREADLINE_BUSY=1".to_string());
    lines.push("    __rsreadline_update down".to_string());
    lines.push("    _RSREADLINE_BUSY=0".to_string());
    lines.push("}".to_string());
    lines.push(String::new());

    lines.push("__rsreadline_insert() {".to_string());
    lines.push("    _RSREADLINE_BUSY=1".to_string());
    lines.push("    local ch=\"$1\"".to_string());
    lines.push(
        "    READLINE_LINE=\"${READLINE_LINE:0:READLINE_POINT}${ch}${READLINE_LINE:READLINE_POINT}\""
            .to_string(),
    );
    lines.push("    READLINE_POINT=$((READLINE_POINT + 1))".to_string());
    lines.push("    __rsreadline_update none".to_string());
    lines.push("    _RSREADLINE_BUSY=0".to_string());
    lines.push("}".to_string());
    lines.push(String::new());

    lines.push("__rsreadline_backspace() {".to_string());
    lines.push("    _RSREADLINE_BUSY=1".to_string());
    lines.push("    if ((READLINE_POINT > 0)); then".to_string());
    lines.push(
        "        READLINE_LINE=\"${READLINE_LINE:0:READLINE_POINT-1}${READLINE_LINE:READLINE_POINT}\""
            .to_string(),
    );
    lines.push("        READLINE_POINT=$((READLINE_POINT - 1))".to_string());
    lines.push("    fi".to_string());
    lines.push("    __rsreadline_update none".to_string());
    lines.push("    _RSREADLINE_BUSY=0".to_string());
    lines.push("}".to_string());
    lines.push(String::new());

    // Only reachable while something is selected (see the dynamic rebind in
    // __rsreadline_update) — Tab is meant to do nothing in that state. But
    // "do nothing" still needs a redraw ("stay": keep the selection exactly
    // as it is) to repaint over the DEBUG-trap preexec hook's harmless
    // spurious clear, which fires before this function's very first
    // statement, before _RSREADLINE_BUSY is set — otherwise the block would
    // visibly vanish until the next real keystroke instead of just staying
    // put. See ARCHITECTURE.md.
    lines.push("__rsreadline_tab_noop() {".to_string());
    lines.push("    _RSREADLINE_BUSY=1".to_string());
    lines.push("    __rsreadline_update stay".to_string());
    lines.push("    _RSREADLINE_BUSY=0".to_string());
    lines.push("}".to_string());
    lines.push(String::new());

    lines.push(r#"bind -x '"\C-?": __rsreadline_backspace'"#.to_string());
    lines.push(r#"bind -x '"\C-h": __rsreadline_backspace'"#.to_string());
    lines.push(String::new());

    for byte in PRINTABLE_ASCII_RANGE {
        lines.push(bind_line_for_char(byte as char));
    }
    lines.push(String::new());

    lines.push("__rsreadline_prompt_reset() {".to_string());
    // Suggestions are matched against `history_file` on disk, but bash only
    // appends to HISTFILE on shell exit — without this, a command just run
    // this session (e.g. re-typing it right after) wouldn't suggest itself
    // until the shell exits. `history -a` flushes new lines from bash's
    // in-memory history to HISTFILE now, before the next prompt/keystroke.
    lines.push("    history -a".to_string());
    lines.push(
        "    # Safety net: if some prior handler invocation didn't reach its own".to_string(),
    );
    lines.push("    # _RSREADLINE_BUSY=0 (e.g. the rsreadline binary errored or hung".to_string());
    lines.push("    # mid-call), don't let the preexec guard stay stuck off forever.".to_string());
    lines.push("    _RSREADLINE_BUSY=0".to_string());
    lines.push(format!("    printf '%s' {clear_seq} > /dev/tty"));
    lines.push("    _RSREADLINE_SEL=\"\"".to_string());
    lines.push("    _RSREADLINE_QUERY=\"\"".to_string());
    lines.push(r#"    bind '"\e[A": previous-history'"#.to_string());
    lines.push(r#"    bind '"\e[B": next-history'"#.to_string());
    lines.push(r#"    bind '"\C-i": complete'"#.to_string());
    lines.push("}".to_string());
    lines.push(
        "PROMPT_COMMAND=\"__rsreadline_prompt_reset${PROMPT_COMMAND:+; }$PROMPT_COMMAND\""
            .to_string(),
    );

    lines.join("\n") + "\n"
}

const PRINTABLE_ASCII_RANGE: std::ops::RangeInclusive<u8> = 0x20..=0x7e;

fn current_exe_string() -> String {
    std::env::current_exe()
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_else(|_| "rsreadline".to_string())
}

/// Wraps `s` as a single-quoted POSIX shell literal, safe for any byte
/// content including embedded single quotes.
fn shell_single_quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('\'');
    for ch in s.chars() {
        if ch == '\'' {
            out.push_str("'\\''");
        } else {
            out.push(ch);
        }
    }
    out.push('\'');
    out
}

/// Wraps `s` as a bash ANSI-C-quoted (`$'...'`) literal, escaping control
/// bytes we're known to emit (ESC, CR, LF) plus backslash/single-quote.
fn dollar_quote(s: &str) -> String {
    let mut out = String::from("$'");
    for b in s.bytes() {
        match b {
            b'\\' => out.push_str("\\\\"),
            b'\'' => out.push_str("\\'"),
            0x1b => out.push_str("\\033"),
            b'\r' => out.push_str("\\r"),
            b'\n' => out.push_str("\\n"),
            0x20..=0x7e => out.push(b as char),
            other => out.push_str(&format!("\\x{other:02x}")),
        }
    }
    out.push('\'');
    out
}

/// Escapes a character for use inside readline's own `"key": command`
/// key-sequence quoting (only `\` and `"` are special there).
fn readline_keyseq_escape(c: char) -> String {
    match c {
        '\\' => "\\\\".to_string(),
        '"' => "\\\"".to_string(),
        other => other.to_string(),
    }
}

fn bind_line_for_char(c: char) -> String {
    let key = readline_keyseq_escape(c);
    let command = format!("__rsreadline_insert {}", shell_single_quote(&c.to_string()));
    let combined = format!("\"{key}\": {command}");
    format!("bind -x {}", shell_single_quote(&combined))
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;
    use std::io::Write;
    use std::process::{Command, Stdio};

    fn default_config() -> Config {
        Config::parse("", None)
    }

    #[test]
    fn one_binding_per_printable_char_plus_special_keys() {
        let script = generate(&default_config());
        let char_bindings = script
            .lines()
            .filter(|l| l.starts_with("bind -x '\"") && l.contains("__rsreadline_insert"))
            .count();
        assert_eq!(char_bindings, 95); // 0x20..=0x7e inclusive

        assert!(script.contains(r#"bind -x '"\C-?": __rsreadline_backspace'"#));
        assert!(script.contains(r#"bind -x '"\C-h": __rsreadline_backspace'"#));
        // Tab starts bound to bash's own native completion, not us — see
        // tab_starts_and_resets_to_native_completion.
        assert!(script.contains(r#"bind '"\C-i": complete'"#));
    }

    #[test]
    fn each_char_binding_is_distinct() {
        let script = generate(&default_config());
        let mut bindings: Vec<&str> = script
            .lines()
            .filter(|l| l.starts_with("bind -x '\"") && l.contains("__rsreadline_insert"))
            .collect();
        let before = bindings.len();
        bindings.sort_unstable();
        bindings.dedup();
        assert_eq!(bindings.len(), before);
    }

    #[test]
    fn special_shell_characters_are_escaped_safely() {
        for c in ['\'', '"', '\\', '`', '$', ' '] {
            let line = bind_line_for_char(c);
            // The whole "keyseq": command segment must be wrapped in a single
            // shell argument (starts right after "bind -x ").
            assert!(line.starts_with("bind -x '"));
            assert!(line.ends_with('\''));
        }
    }

    #[test]
    fn generated_script_is_valid_bash_syntax() {
        let script = generate(&default_config());
        let mut child = Command::new("bash")
            .arg("-n")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("bash must be available to run this test");
        child
            .stdin
            .take()
            .expect("stdin")
            .write_all(script.as_bytes())
            .expect("write script to bash -n");
        let output = child.wait_with_output().expect("bash -n exited");
        assert!(
            output.status.success(),
            "bash -n failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

    #[test]
    fn shell_single_quote_handles_embedded_quotes() {
        assert_eq!(shell_single_quote("it's"), "'it'\\''s'");
    }

    #[test]
    fn dollar_quote_escapes_escape_byte() {
        let q = dollar_quote("\x1b[2K");
        assert_eq!(q, "$'\\033[2K'");
    }

    #[test]
    fn bind_tty_special_chars_is_disabled() {
        // Otherwise readline keeps re-binding whatever key stty erase points
        // to (Backspace) back to its own default, ignoring our bind -x for
        // it — see ARCHITECTURE.md.
        let script = generate(&default_config());
        assert!(script.contains("bind 'set bind-tty-special-chars off'"));
    }

    #[test]
    fn tab_dynamically_rebinds_between_native_completion_and_noop() {
        let script = generate(&default_config());
        // Initial state (nothing selected): native completion.
        assert!(script.contains(r#"bind '"\C-i": complete'"#));
        // __rsreadline_update flips it based on _RSREADLINE_SEL.
        assert!(script.contains(r#"bind -x '"\C-i": __rsreadline_tab_noop'"#));
        assert!(script.contains("if [[ -n \"$_RSREADLINE_SEL\" ]]; then"));
        // prompt_reset resets it back to native for the next line too.
        let prompt_reset_start = script
            .find("__rsreadline_prompt_reset() {")
            .expect("prompt_reset not found");
        let body_end = script[prompt_reset_start..]
            .find("\n}")
            .expect("prompt_reset has no closing brace");
        assert!(
            script[prompt_reset_start..prompt_reset_start + body_end]
                .contains(r#"bind '"\C-i": complete'"#)
        );
    }

    #[test]
    fn debug_trap_and_preexec_guard_are_wired_up() {
        let script = generate(&default_config());
        assert!(script.contains("_RSREADLINE_BUSY=0"), "initial declaration");
        assert!(script.contains("__rsreadline_preexec() {"));
        assert!(script.contains("trap __rsreadline_preexec DEBUG"));
        assert!(script.contains("[[ \"$_RSREADLINE_BUSY\" == 1 ]] && return"));
    }

    #[test]
    fn every_bind_x_entry_handler_sets_and_clears_the_busy_guard() {
        // Every function bound directly via `bind -x` (as opposed to
        // __rsreadline_update, which is only ever called from one of these)
        // must set _RSREADLINE_BUSY=1 as its first real action and reset it
        // to 0 before returning, so __rsreadline_preexec's guard check is
        // accurate for the whole duration of the handler — see the "Why this
        // trap exists" comment block in `generate`.
        let script = generate(&default_config());
        for func in [
            "__rsreadline_up",
            "__rsreadline_down",
            "__rsreadline_insert",
            "__rsreadline_backspace",
            "__rsreadline_tab_noop",
        ] {
            let start = script
                .find(&format!("{func}() {{"))
                .unwrap_or_else(|| panic!("{func} not found in generated script"));
            let body_end = script[start..]
                .find("\n}")
                .unwrap_or_else(|| panic!("{func} has no closing brace"));
            let body = &script[start..start + body_end];
            assert!(
                body.contains("_RSREADLINE_BUSY=1"),
                "{func} must set the busy guard"
            );
            assert!(
                body.contains("_RSREADLINE_BUSY=0"),
                "{func} must clear the busy guard before returning"
            );
        }
    }

    #[test]
    fn prompt_reset_resets_the_busy_guard_as_a_safety_net() {
        let script = generate(&default_config());
        let start = script
            .find("__rsreadline_prompt_reset() {")
            .expect("prompt_reset not found");
        let body_end = script[start..]
            .find("\n}")
            .expect("prompt_reset has no closing brace");
        let body = &script[start..start + body_end];
        assert!(body.contains("_RSREADLINE_BUSY=0"));
    }
}
